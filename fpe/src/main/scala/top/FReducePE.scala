package cute

import chisel3._
import chisel3.util._
import org.chipsalliance.cde.config.Parameters

/**
  * SystemVerilog implementation boundary.  Its explicit clock/reset ports
  * match CuteFpeSv.sv, while FReducePE below preserves the original CUTE
  * Scala-facing interface.
  */
private class CuteFpeSvBlackBox(implicit val p: Parameters)
    extends BlackBox with HasBlackBoxPath with CUTEImplParameters {

  // The external SV FPE supports one compile-time width per build.  Keeping
  // these checks here makes a CUTE/SV port-width mismatch fail during
  // elaboration instead of producing incompatible Verilog.
  require(ReduceWidth == 256 || ReduceWidth == 512)
  require(ScaleWidth == ReduceWidth / 8)

  override def desiredName: String = "CuteFpeSv"

  val io = IO(new Bundle {
    val clock = Input(Clock())
    val reset = Input(Bool())
    val AVector = Flipped(DecoupledIO(UInt(ReduceWidth.W)))
    val BVector = Flipped(DecoupledIO(UInt(ReduceWidth.W)))
    val CAdd = Flipped(DecoupledIO(UInt(ResultWidth.W)))
    val AScale = Flipped(DecoupledIO(UInt(ScaleWidth.W)))
    val BScale = Flipped(DecoupledIO(UInt(ScaleWidth.W)))
    val DResult = DecoupledIO(UInt(ResultWidth.W))
    val opcode = Input(UInt(ElementDataType.DataTypeBitWidth.W))
  })

  private def findCuteRoot(start: java.io.File): java.io.File = {
    Iterator
      .iterate(start.getCanonicalFile)(_.getParentFile)
      .takeWhile(_ != null)
      .find { dir =>
        new java.io.File(dir, "cute-fpe").isDirectory &&
        new java.io.File(dir, "src/main/scala/MatrixTE.scala").isFile
      }
      .getOrElse {
        throw new IllegalStateException(
          s"Cannot find the CUTE repository root from ${start.getAbsolutePath}"
        )
      }
  }

  private val cuteRoot =
    findCuteRoot(new java.io.File(System.getProperty("user.dir")))

  private val rtlDir =
    new java.io.File(cuteRoot, "cute-fpe/rtl/fpe/rtl")

  private val generatedConfig =
    new java.io.File(rtlDir, "CuteFpeConfig.svh")

  private val generatedConfigContents =
    s"""|// Auto-generated by FReducePE from CUTE CuteParams. Do not edit.
        |`ifndef CUTE_FPE_CONFIG_SVH
        |`define CUTE_FPE_CONFIG_SVH
        |
        |`define ReduceWidth       $ReduceWidth
        |`define ResultWidth       $ResultWidth
        |`define MinGroupSize      $MinGroupSize
        |`define MinDataTypeWidth  $MinDataTypeWidth
        |`define ScaleElementWidth $ScaleElementWidth
        |`define ScaleBusWidth     $ScaleWidth
        |`define cmptreelayers     $cmptreelayers
        |`define fp8cmptreelayers  $fp8cmptreelayers
        |`define FP4P0AddNum       $FP4P0AddNum
        |
        |`endif
        |""".stripMargin

  private val generatedConfigBytes =
    generatedConfigContents.getBytes(java.nio.charset.StandardCharsets.US_ASCII)

  private val generatedConfigIsCurrent =
    generatedConfig.isFile && java.util.Arrays.equals(
      java.nio.file.Files.readAllBytes(generatedConfig.toPath),
      generatedConfigBytes
    )

  if (!generatedConfigIsCurrent) {
    java.nio.file.Files.write(generatedConfig.toPath, generatedConfigBytes)
  }

  private val rtlFiles = Option(rtlDir.listFiles()).getOrElse {
    throw new IllegalStateException(
      s"SV FPE RTL directory is missing or unreadable: ${rtlDir.getAbsolutePath}"
    )
  }.filter(file => file.isFile && file.getName.endsWith(".sv"))
    .sortBy(_.getName)

  require(
    rtlFiles.nonEmpty,
    s"No SystemVerilog files found in ${rtlDir.getAbsolutePath}"
  )

  addPath(generatedConfig.getAbsolutePath)
  rtlFiles.foreach(file => addPath(file.getAbsolutePath))
}

/**
  * Drop-in replacement for the original Chisel FReducePE.
  *
  * MatrixTE continues to instantiate new FReducePE() and sees the same data
  * ports as before.  Only this wrapper knows that the implementation is an
  * external SystemVerilog BlackBox.
  */
class FReducePE(implicit p: Parameters) extends CuteModule {
  val io = IO(new Bundle {
    val AVector = Flipped(DecoupledIO(UInt(ReduceWidth.W)))
    val BVector = Flipped(DecoupledIO(UInt(ReduceWidth.W)))
    val CAdd = Flipped(DecoupledIO(UInt(ResultWidth.W)))
    val AScale = Flipped(DecoupledIO(UInt(ScaleWidth.W)))
    val BScale = Flipped(DecoupledIO(UInt(ScaleWidth.W)))
    val DResult = DecoupledIO(UInt(ResultWidth.W))
    val opcode = Input(UInt(ElementDataType.DataTypeBitWidth.W))
  })

  private val svFpe = Module(new CuteFpeSvBlackBox)

  // CuteModule supplies the normal CUTE clock/reset; the SV module exposes
  // them as explicit input ports.
  svFpe.io.clock := clock
  svFpe.io.reset := reset.asBool

  svFpe.io.AVector.bits := io.AVector.bits
  svFpe.io.AVector.valid := io.AVector.valid
  io.AVector.ready := svFpe.io.AVector.ready

  svFpe.io.BVector.bits := io.BVector.bits
  svFpe.io.BVector.valid := io.BVector.valid
  io.BVector.ready := svFpe.io.BVector.ready

  svFpe.io.CAdd.bits := io.CAdd.bits
  svFpe.io.CAdd.valid := io.CAdd.valid
  io.CAdd.ready := svFpe.io.CAdd.ready

  svFpe.io.AScale.bits := io.AScale.bits
  svFpe.io.AScale.valid := io.AScale.valid
  io.AScale.ready := svFpe.io.AScale.ready

  svFpe.io.BScale.bits := io.BScale.bits
  svFpe.io.BScale.valid := io.BScale.valid
  io.BScale.ready := svFpe.io.BScale.ready

  svFpe.io.opcode := io.opcode

  io.DResult.bits := svFpe.io.DResult.bits
  io.DResult.valid := svFpe.io.DResult.valid
  svFpe.io.DResult.ready := io.DResult.ready
}
